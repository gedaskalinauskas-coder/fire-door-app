#!/usr/bin/env python3
"""Sync the install / PWA files with the BRAND block in index.html (white-label).
Run from anywhere after editing BRAND:   python3 tools/build-pwa.py [--icons]
  - writes manifest.webmanifest (names + theme/background colours from BRAND)
  - copies the brand values invite.html needs into its /*BRAND:start*/ block
  - copies the qrcode-generator library from index.html into invite.html's /*QRLIB:start*/ block
  - --icons: also rebuilds the PWA icons from icons/apple-touch-icon.png (tools/make-icons.py)
Remember to bump VERSION in sw.js when you change any app file, so phones pick up the update."""
import re, os, sys, json, subprocess
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = lambda f: os.path.join(ROOT, f)
src = open(P('index.html'), encoding='utf-8').read()
block = re.search(r"const BRAND=\{(.*?)\n\};", src, re.S).group(1)
def s(k):
    m = re.search(r"\b" + k + r":'((?:[^'\\]|\\.)*)'", block)
    return m.group(1) if m else ''
colors = dict(re.findall(r"(\w+):'(#[0-9a-fA-F]{3,8})'", re.search(r"colors:\{(.*?)\}", block, re.S).group(1)))
B = {k: s(k) for k in ('name', 'companyNo', 'copyrightYear', 'short', 'appName', 'appShort', 'appSubtitle', 'headerLogo')}
B['colors'] = {k: colors[k] for k in ('black', 'yellow', 'pink', 'ink')}
B['inviteLine'] = 'Fire door surveys on site – photos, gap checks and PDF reports, even offline.'

manifest = {
    "id": "./index.html",
    "name": B['appName'],
    "short_name": B['appShort'] or B['appName'],
    "description": f"{B['appName']}: record fire doors on site and produce PDF reports.",
    "lang": "en-GB",
    "dir": "ltr",
    "start_url": "./index.html",
    "scope": "./",
    "display": "standalone",
    "orientation": "any",
    "theme_color": B['colors']['black'],
    "background_color": B['colors']['black'],
    "categories": ["business", "productivity", "utilities"],
    "icons": [
        {"src": "icons/icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any"},
        {"src": "icons/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any"},
        {"src": "icons/icon-maskable-192.png", "sizes": "192x192", "type": "image/png", "purpose": "maskable"},
        {"src": "icons/icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
        {"src": "icons/apple-touch-icon.png", "sizes": "180x180", "type": "image/png", "purpose": "any"}
    ]
}
open(P('manifest.webmanifest'), 'w', encoding='utf-8').write(json.dumps(manifest, indent=2, ensure_ascii=False) + '\n')

inv = open(P('invite.html'), encoding='utf-8').read()
brand_js = ('/* generated by tools/build-pwa.py from BRAND in index.html - do not edit here */\n'
            'const BRAND=' + json.dumps(B, ensure_ascii=False) + ';\n')
inv = re.sub(r"/\*BRAND:start\*/.*?/\*BRAND:end\*/", lambda m: '/*BRAND:start*/\n' + brand_js + '/*BRAND:end*/', inv, flags=re.S)
lib = re.search(r"(/\*! qrcode-generator.*?)\n</script>", src, re.S).group(1)
inv = re.sub(r"/\*QRLIB:start\*/.*?/\*QRLIB:end\*/", lambda m: '/*QRLIB:start*/\n' + lib + '\n/*QRLIB:end*/', inv, flags=re.S)
inv = re.sub(r'(<meta name="theme-color" content=")[^"]*', lambda m: m.group(1) + B['colors']['black'], inv)
inv = re.sub(r'(<meta name="apple-mobile-web-app-title" content=")[^"]*', lambda m: m.group(1) + (B['appShort'] or B['appName']), inv)
open(P('invite.html'), 'w', encoding='utf-8').write(inv)
if '--icons' in sys.argv:
    subprocess.check_call([sys.executable, P('tools/make-icons.py')])
print('manifest.webmanifest + invite.html updated from BRAND')
